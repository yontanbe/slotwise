/**
 * Accessibility suite (axe-core + keyboard-only flows).
 *
 * Every route is scanned once per describe block (WCAG 2.0 A/AA, 2.1 AA, 2.2 AA) and then one test per
 * rule asserts it is clean. Rules that are currently violated are listed in DEBT and their tests are
 * marked test.fail(), so the suite stays green while documenting the exact debt. When a rule gets fixed
 * its test "unexpectedly passes" and turns red: delete the entry from DEBT.
 *
 * Run: PW_PORT=4191 npx playwright test tests/e2e/a11y.spec.ts --trace off --project=desktop
 */
