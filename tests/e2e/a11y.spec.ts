/**
 * Known violations, keyed by `${mode} ${route}`. Each entry: rule id -> what is wrong (see report).
 *  - color-contrast (light): --ink-3 #6b6f80 on --paper #f6efe1 = 4.35:1, on --paper-2 #eee4cf = 3.95:1;
 *    --on-accent #fff8ef on --accent #e4572e = 3.49:1 (.btn-accent, .avatar); .stamp.ok #3e7f5a @ opacity .9 = 3.7:1.
 *  - color-contrast (dark): --ok/--danger are not redefined for dark: .stamp.ok 3.3:1, .btn-danger 3.14:1 / 2.82:1;
 *    .folder uses #fff on the event color #e4572e = 3.68:1.
 *  - label: <Field> renders <label> without htmlFor and without wrapping the control (src/components/ui.tsx Field).
 *  - select-name: <select> with no label (TimezoneSelect, Bookings filter, EventTypeEditor location selects, Settings).
 *  - button-name / link-name: .icon-btn with only an <Icon> (aria-hidden svg) and no aria-label/title; <Toggle> without label.
 *  - aria-required-children: MonthCalendar .month-grid role="grid" without row/gridcell children.
 *  - aria-allowed-attr: Availability schedule tabs use aria-selected on plain buttons (no role="tab"/tablist).
 */
// All axe rules pass on every route; add entries here only to document new, known debt.
const DEBT: Record<string, string[]> = {}

// Rules checked as their own test for every route even when not in DEBT (the ones most likely to regress).
const WATCHED = ['color-contrast', 'label', 'select-name', 'button-name', 'link-name', 'aria-required-children', 'aria-allowed-attr', 'target-size']

/** Marks a test as known debt. Set A11Y_STRICT=1 to see the real failures instead. */
function knownDebt(why: string) {
  if (!process.env.A11Y_STRICT) test.fail(true, why)
}

async function setMode(page: Page, mode: Mode) {
  if (mode === 'en-dark')
    await page.addInitScript(() => {
      localStorage.setItem('slotwise:locale', 'en')
      localStorage.setItem('slotwise:theme', 'dark')
    })
}

async function open(page: Page, route: string) {
  if (route === POLL) {
    await go(page, '/')
    const id = await page.evaluate(() => JSON.parse(localStorage.getItem('slotwise:db') || '{}').polls?.[0]?.id)
    await go(page, '/p/' + id)
  } else if (route === MANAGE) {
    await go(page, '/yonatan/intro')
    await pickFirstSlot(page)
    await fillInvitee(page, 'Axe Tester', `axe.${Date.now()}@test.dev`)
    await page.locator('form.booker-form button.btn-accent.btn-lg').click()
    await expect(page).toHaveURL(/#\/b\//, { timeout: 15_000 })
  } else if (route === BOOK_FORM) {
    await go(page, '/yonatan/consult')
    await pickFirstSlot(page)
  } else if (route === ET) {
    const id = await page.evaluate(() => JSON.parse(localStorage.getItem('slotwise:db') || '{}').eventTypes?.[0]?.id)
    await go(page, '/app/event-types/' + id)
  } else {
    await go(page, route)
  }
  // let rise/fade-in animations settle so contrast is measured at rest
  await page.waitForLoadState('networkidle')
  await page.waitForTimeout(700)
}

async function scan(page: Page): Promise<Violation[]> {
  const r = await new AxeBuilder({ page }).withTags(TAGS).analyze()
  return r.violations
}

function describeNodes(v: Violation) {
  return `${v.id} (${v.nodes.length}): ` + v.nodes.slice(0, 8).map((n) => `\n  ${n.target.join(' ')} :: ${(n.failureSummary || '').replace(/\s+/g, ' ').slice(0, 200)}`).join('')
}

function suite(mode: Mode, routes: string[], needsLogin: boolean) {
  for (const route of routes) {
    const key = `${mode} ${route}`
    test.describe(`axe ${key}`, () => {
      let violations: Violation[] = []
      test.beforeAll(async ({ browser }: { browser: Browser }) => {
        test.setTimeout(90_000)
        const ctx = await browser.newContext({ ...devices['Desktop Chrome'], viewport: { width: 1360, height: 900 }, locale: 'he-IL', timezoneId: 'Asia/Jerusalem', baseURL: test.info().project.use.baseURL })
        const page = await ctx.newPage()
        await setMode(page, mode)
        if (needsLogin) await enterDemo(page)
        await open(page, route)
        violations = await scan(page)
        await ctx.close()
      })

      const debt = DEBT[key] || []
      for (const rule of new Set([...WATCHED, ...debt])) {
        test(rule, () => {
          if (debt.includes(rule)) knownDebt(`known a11y debt: ${rule} on ${key}`)
          const v = violations.find((x) => x.id === rule)
          expect(v, v && describeNodes(v)).toBeUndefined()
        })
      }
      test('no other WCAG violations', () => {
        const other = violations.filter((v) => !WATCHED.includes(v.id) && !debt.includes(v.id))
        expect(other.map(describeNodes)).toEqual([])
      })
    })
  }
}

test.describe.configure({ mode: 'default' })

suite('he-light', PUBLIC, false)
suite('he-light', APP, true)
suite('en-dark', EN_DARK_SAMPLE.filter((r) => PUBLIC.includes(r)), false)
suite('en-dark', EN_DARK_SAMPLE.filter((r) => APP.includes(r)), true)

/* ------------------------------------------------------------------ keyboard-only flows */

const focusedInfo = (page: Page) =>
  page.evaluate(() => {
    const a = document.activeElement as HTMLElement | null
    return { tag: a?.tagName.toLowerCase() || '', cls: a?.className?.toString() || '', text: (a?.innerText || a?.getAttribute('data-date') || '').trim().slice(0, 40) }
  })

/** Tab forward until predicate matches the focused element (max n presses). */
async function tabTo(page: Page, match: (el: Element) => boolean, n = 80) {
  const fn = match.toString()
  for (let i = 0; i < n; i++) {
    await page.keyboard.press('Tab')
    const ok = await page.evaluate((src) => {
      const f = new Function('return ' + src)() as (el: Element) => boolean
      return !!document.activeElement && f(document.activeElement)
    }, fn)
    if (ok) return true
  }
  return false
}

