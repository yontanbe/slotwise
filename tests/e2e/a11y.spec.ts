test.describe('mobile (Pixel 7)', () => {
  const { defaultBrowserType: _b, ...pixel } = devices['Pixel 7']
  test.use(pixel)

  for (const route of ['/', '/yonatan/intro', BOOK_FORM, '/app', '/app/bookings']) {
    test(`tap targets >= 24px on ${route}`, async ({ page }) => {
      if (route.startsWith('/app')) await enterDemo(page)
      await open(page, route)
      const small = await page.evaluate(() =>
        Array.from(document.querySelectorAll<HTMLElement>('a[href], button, input:not([type=hidden]), select, textarea, [role=button], [role=switch], [tabindex]:not([tabindex="-1"])'))
          .filter((el) => el.offsetParent !== null && !el.classList.contains('sr-only'))
          .map((el) => ({ el, r: el.getBoundingClientRect() }))
          .filter(({ r }) => r.width > 0 && (r.width < 24 || r.height < 24))
          .map(({ el, r }) => `${el.tagName.toLowerCase()}.${el.className.toString().split(' ').join('.')} "${(el.innerText || el.getAttribute('data-date') || '').trim().slice(0, 20)}" ${Math.round(r.width)}x${Math.round(r.height)}`),
      )
      test.info().annotations.push({ type: 'small-targets', description: small.join('\n') })
      if (MOBILE_SMALL_TARGET_DEBT.includes(route)) knownDebt('targets under 24x24 CSS px, see annotation')
      expect(small).toEqual([])
    })
  }
})

